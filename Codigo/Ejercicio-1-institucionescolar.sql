CREATE DATABASE InstitucionEscolar;
GO

USE InstitucionEscolar;
GO

CREATE TABLE PROFESORES (
    LEGAJO_PR INT PRIMARY KEY,
    NOMBRE_PR VARCHAR(50),
    APELLIDO_PR VARCHAR(50),
    DNI_PR VARCHAR(20),
    DIRECCION_PR VARCHAR(150),
    CIUDAD_PR VARCHAR(50),
    TELEFONO_PR VARCHAR(30),
    TITULO_PR VARCHAR(100),
    SUELDO_PR DECIMAL(10,2),
    CBU_PR VARCHAR(22)
);

CREATE TABLE CURSOS (
    CONCUR_CUR INT PRIMARY KEY,
    LEGAJOPRO_CUR INT,
    DURACION_CUR INT,
    IMPORTE_CUR DECIMAL(10,2),
    CANTALUMNOS_CUR INT,
    FOREIGN KEY (LEGAJOPRO_CUR) REFERENCES PROFESORES(LEGAJO_PR)
);

CREATE TABLE ALUMNOS (
    DNI_AL VARCHAR(20) PRIMARY KEY,
    LEGAJO_AL INT,
    NOMBRE_AL VARCHAR(50),
    TELEFONO_AL VARCHAR(30),
    DIRECCION_AL VARCHAR(150)
);

CREATE TABLE CURXALU (
    CONCUR_CXA INT,
    DNI_AL_CXA VARCHAR(20),
    NOTA_1P_CXA DECIMAL(4,2),
    NOTA_2P_CXA DECIMAL(4,2),
    PRIMARY KEY (CONCUR_CXA, DNI_AL_CXA),
    FOREIGN KEY (CONCUR_CXA) REFERENCES CURSOS(CONCUR_CUR),
    FOREIGN KEY (DNI_AL_CXA) REFERENCES ALUMNOS(DNI_AL)
);